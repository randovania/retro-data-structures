_BASE_NAME_SUFFIX = re.compile(r"_0x[0-9a-f]{8}$")


def hex_id(value: int) -> str:
    return f"0x{value:X}"


def games_expr(games: typing.Iterable[Game]) -> str:
    games = sorted(set(games), key=lambda g: g.value)
    if len(games) == len(GAMES):
        return "ALL_GAMES"
    return " | ".join(GAME_CONST[g] for g in games)


def wrap_call(prefix: str, args: list[str], suffix: str = "") -> str:
    """`prefix(args)suffix` on one line if it fits, otherwise in the style of black. `prefix` includes the indentation."""
    one_line = f"{prefix}({', '.join(args)}){suffix}"
    if len(one_line) <= LINE_LENGTH or not args:
        return one_line
    indent = prefix[: len(prefix) - len(prefix.lstrip())]
    inner = ", ".join(args)
    if len(indent) + 4 + len(inner) <= LINE_LENGTH:
        return f"{prefix}(\n{indent}    {inner}\n{indent}){suffix}"
    body = "".join(f"{indent}    {a},\n" for a in args)
    return f"{prefix}(\n{body}{indent}){suffix}"


def fill_lines(entries: list[str], indent: str) -> list[str]:
    """Entries separated by commas, put on as few lines as fit."""
    lines: list[str] = []
    current = indent
    for entry in entries:
        piece = entry + ","
        if current.strip() and len(current) + 1 + len(piece) > LINE_LENGTH:
            lines.append(current)
            current = indent + piece
        else:
            current = current + (" " if current.strip() else "") + piece
    if current.strip():
        lines.append(current)
    return lines


@dataclasses.dataclass
class Names:
    """Final names of classes and enums, unique in the whole package."""

    classes: dict[str, str]
    enums: dict[EnumKey, str]


def resolve_names(merged: Merged) -> Names:
    taken: set[str] = set(RESERVED_NAMES) | CODEC_HELPERS
    classes: dict[str, str] = {}
    for name in sorted(merged.classes):
        final = name
        while final in taken:
            final += "Struct" if merged.classes[name].kind == "struct" else "_"
        taken.add(final)
        classes[name] = final
        merged.classes[name].final_name = final

    enums: dict[EnumKey, str] = {}

    def unique(base: str, kind: str, owner: str | None) -> str:
        candidates = [base, base + ("Flags" if kind == "flags" else "Enum")]
        if owner is not None:
            candidates += [owner + base, owner + base + ("Flags" if kind == "flags" else "Enum")]
        for candidate in candidates:
            if candidate not in taken:
                return candidate
        candidate = candidates[-1]
        while candidate in taken:
            candidate += "_"
        return candidate

    shared = sorted(k for k in merged.enums if k[0] == "shared")
    for key in shared:
        e = merged.enums[key]
        final = unique(e.name, e.kind, None)
        taken.add(final)
        enums[key] = final
        e.final_name = final

    local = sorted(k for k in merged.enums if k[0] == "local")
    base_counts = collections.Counter(k[2] for k in local)
    for key in local:
        e = merged.enums[key]
        if base_counts[key[2]] > 1 or key[2] in taken:
            final = unique(key[1] + e.name, e.kind, None)
        else:
            final = unique(e.name, e.kind, key[1])
        taken.add(final)
        enums[key] = final
        e.final_name = final
    return Names(classes, enums)


# Enums


def render_enum(e: MEnum) -> list[str]:
    bases = {"IntEnum": "enum.IntEnum", "IntFlag": "enum.IntFlag", "Enum": "enum.Enum"}[e.base]
    if e.allow_unknown:
        bases = "AllowUnknownValues, " + bases
    lines = [f"class {e.final_name}({bases}):"]
    for name in e.members:
        lines.append(f"    {name} = {lit(e.canonical[name])}")
    if not e.plain:
        lines.append("")
        lines.append("    # fmt: off")
        lines.append("    __game_values__ = {")
        for game in GAMES:
            if game not in e.game_values:
                continue
            entries = [f"{lit(n)}: {lit(v)}" for n, v in e.game_values[game].items()]
            lines.append(f"        Game.{game.name}: {{")
            lines.extend(fill_lines(entries, " " * 12))
            lines.append("        },")
        lines.append("    }")
        lines.append("    # fmt: on")
    return lines


def enum_file(enums: list[MEnum]) -> str:
    parts = [HEADER, "from __future__ import annotations\n", "import enum\n"]
    imports = ["from retro_data_structures.game_check import Game"] if any(not e.plain for e in enums) else []
    if any(e.allow_unknown for e in enums):
        imports.append("from retro_data_structures.enums.merged import AllowUnknownValues")
    imports.sort(key=lambda s: s.split()[1])
    if imports:
        parts.append("\n".join(imports) + "\n")
    for e in enums:
        parts.append("\n" + "\n".join(render_enum(e)) + "\n")
    return "\n".join(parts).replace("\n\n\n\n", "\n\n\n")


# Classes


class ModuleBuilder:
    """Collects the imports of a module while its classes are rendered."""

    def __init__(self, merged: Merged, names: Names, module: str, package: str):
        self.merged = merged
        self.names = names
        self.module = module
        self.package = package
        self.codec_names: set[str] = set()
        self.constants: set[str] = set()
        self.core: set[str] = set()
        self.class_imports: set[tuple[str, str]] = set()  # (module path, name)
        self.bases: set[str] = set()
        self.shadowed: set[str] = set()
        self.defined: set[str] = set()

    # Names

    def codec_name(self, name: str) -> str:
        self.codec_names.add(name)
        return "_" + name if name in self.shadowed else name

    def enum_ref(self, key: EnumKey) -> str:
        e = self.merged.enums[key]
        final = self.names.enums[key]
        if e.owner is not None:
            owner = self.merged.classes[e.owner]
            module = self.module_path(owner)
            if module != self.module:
                self.class_imports.add((module, final))
        else:
            self.class_imports.add(("retro_data_structures.enums", final))
        return final

    def module_path(self, cls: MClass) -> str:
        if cls.placement == "archetypes":
            return f"{PACKAGE}.archetypes.{cls.final_name}"
        root = cls.final_name if cls.placement == "objects" else self.names.classes[cls.placement]
        return f"{PACKAGE}.objects.{root}"

    def struct_ref(self, name: str) -> str:
        cls = self.merged.classes[name]
        module = self.module_path(cls)
        if module != self.module:
            self.class_imports.add((module, cls.final_name))
        return cls.final_name

    # Expressions

    def type_annotation(self, codec: Codec) -> str:
        match codec.type_key():
            case ("int",):
                return "int"
            case ("float",) | ("bool",) | ("str",) | ("bytes",):
                return codec.type_key()[0]
            case ("Vector",) | ("Color",) | ("Spline",) | ("AnimationParameters",):
                name = codec.type_key()[0]
                self.core.add(name)
                return name
            case ("enum", key):
                return self.enum_ref(key)
            case ("struct", name):
                return self.struct_ref(name)
            case _:
                assert codec.inner is not None
                return f"list[{self.type_annotation(codec.inner)}]"

    def value(self, value: Value, game: Game) -> tuple[str, bool]:
        """Source of a default and whether it's a factory."""
        if value.kind == "py":
            if value.expr.startswith("Vector("):
                self.core.add("Vector")
            elif value.expr.startswith("Color("):
                self.core.add("Color")
            return value.expr, value.factory
        e = self.merged.enums[value.ref]
        name = self.enum_ref(value.ref)
        if value.kind == "enum":
            member = e.game_member(game, value.raw)
            assert member is not None, (e.key, value.raw)
            return f"{name}.{member}", False
        return f"{name}({e.canonical_flags(game, value.raw)})", False

    def codec(self, codec: Codec, game: Game) -> str:
        kind = codec.kind
        if kind == "asset":
            args = [lit(t) for t in codec.args]
            if codec.flag:
                args.append("ignore_dependencies_mlvl=True")
            return f"{self.codec_name('asset')}({', '.join(args)})"
        if kind in ("enum_", "flags_"):
            return f"{self.codec_name(kind)}({self.enum_ref(codec.ref)})"
        if kind == "struct":
            name = self.struct_ref(codec.ref)
            args = [name]
            if codec.defaults:
                items = ", ".join(f"{lit(field)}: {self.value(v, game)[0]}" for field, v in codec.defaults)
                args.append(f"defaults={{{items}}}")
            if codec.cooks:
                items = ", ".join(f"{lit(field)}: {lit(cook)}" for field, cook in codec.cooks)
                args.append(f"cooks={{{items}}}")
            return f"{self.codec_name('struct')}({', '.join(args)})"
        if kind == "array":
            assert codec.inner is not None
            return f"{self.codec_name('array')}({self.codec(codec.inner, game)})"
        return self.codec_name(kind)

    def derived_default(self, codec: Codec, game: Game) -> tuple[str, bool] | None:
        match codec.kind:
            case "f32":
                return "0.0", False
            case "bool_":
                return "False", False
            case "sound":
                return "65535", False
            case "string":
                return '""', False
            case "guid":
                return "bytes(16)", False
            case "asset":
                return ("0xFFFFFFFF" if game.uses_asset_id_32 else "0xFFFFFFFFFFFFFFFF"), False
            case "vector":
                self.core.add("Vector")
                return "Vector()", True
            case "color":
                self.core.add("Color")
                return "Color()", True
            case "spline":
                self.core.add("Spline")
                return "Spline()", True
            case "animation_parameters":
                self.core.add("AnimationParameters")
                return "AnimationParameters()", True
            case "struct":
                return self.struct_ref(codec.ref) + "()", True
            case "array":
                return "[]", True
            case "enum_" | "flags_":
                return None
            case _:
                return "0", False

    def prime_locator(self, spec: typing.Any) -> str:
        if isinstance(spec, PrimeEditorSpec):
            if (spec.name, spec.position, spec.rotation, spec.scale, spec.active) == (0, 1, 2, 3, None):
                self.constants.add("EDITOR_PROPERTIES")
                return "EDITOR_PROPERTIES"
            self.constants.add("PrimeEditor")
            parts = []
            for field, default in (("name", 0), ("position", 1), ("rotation", 2), ("scale", 3), ("active", None)):
                value = getattr(spec, field)
                if value != default:
                    parts.append(f"{field}={value}")
            return f"PrimeEditor({', '.join(parts)})"
        return str(spec)

    def game_const(self, game: Game) -> str:
        self.constants.add(GAME_CONST[game])
        return GAME_CONST[game]

    def games_expr(self, games: typing.Iterable[Game]) -> str:
        expr = games_expr(games)
        for part in expr.split(" | "):
            self.constants.add(part)
        return expr

    def render_field(self, cls: MClass, field: MField) -> str:  # noqa: C901, PLR0912, PLR0915
        layouts = field.layouts
        games = field.games
        newest = layouts[games[-1]]
        annotation = self.type_annotation(newest.codec)

        # Codecs
        codec_src = {g: self.codec(layouts[g].codec, g) for g in games}
        base_codec = collections.Counter(codec_src.values()).most_common(1)[0][0]
        for g in games:  # the first of the most common
            if codec_src[g] == base_codec:
                break
        args = [base_codec]

        # Locators
        locators = {g: layouts[g].locator for g in games if layouts[g].locator is not None}
        id_games = [g for g in ID_TAGGED if g in locators]
        if len(id_games) == 2 and locators[Game.ECHOES] == locators[Game.CORRUPTION]:
            args.append(f"id={hex_id(locators[Game.ECHOES])}")
        else:
            for g in id_games:
                args.append(f"{g.name.lower()}={hex_id(locators[g])}")
        if Game.PRIME in locators:
            prime = self.prime_locator(locators[Game.PRIME])
            min_count = layouts[Game.PRIME].min_count
            args.append(f"prime={prime}" if min_count is None else f"prime=({prime}, {min_count})")
        if set(locators) != set(games):
            args.append(f"games={self.games_expr(games)}")

        # Defaults
        effective: dict[Game, tuple[str, bool]] = {}
        derived: dict[Game, bool] = {}
        for g in games:
            lay = layouts[g]
            auto = self.derived_default(lay.codec, g)
            if lay.default is None:
                assert auto is not None, (cls.name, field.name)
                effective[g] = auto
                derived[g] = True
            else:
                effective[g] = self.value(lay.default, g)
                derived[g] = effective[g] == auto
        if len({effective[g] for g in games}) > 1:
            # The games disagree: no game's default is the field's default. List all of them, unless they are all the
            # codec's (for example, the invalid asset id of each game).
            self.constants.add("UNSET")
            args.append("default=UNSET")
            if not all(derived.values()):
                items = ", ".join(f"{self.game_const(g)}: {effective[g][0]}" for g in games)
                args.append(f"defaults={{{items}}}")
        elif not all(derived.values()):
            expr, is_factory = effective[games[0]]
            args.append(f"default_factory=lambda: {expr}" if is_factory else f"default={expr}")
        # Codecs of some games
        other_codecs = {g: s for g, s in codec_src.items() if s != base_codec}
        if other_codecs:
            items = ", ".join(f"{self.game_const(g)}: {s}" for g, s in other_codecs.items())
            args.append(f"codecs={{{items}}}")

        # Cook, order, only_if
        cooks = {g: layouts[g].cook for g in games}
        if any(c != "Always" for c in cooks.values()):
            cook_counts: collections.Counter[str] = collections.Counter(cooks.values())
            base_cook = max(cook_counts, key=lambda c: (cook_counts[c], c == "Always"))
            if base_cook != "Always":
                args.append(f"cook={lit(base_cook)}")
            others = {g: c for g, c in cooks.items() if c != base_cook}
            if others:
                args.append("cooks={" + ", ".join(f"{self.game_const(g)}: {lit(c)}" for g, c in others.items()) + "}")
        if cls.order_games:
            orders = {g: game_order(cls, g).index(field.name) for g in cls.order_games if g in layouts}
            if orders:
                args.append("order={" + ", ".join(f"{self.game_const(g)}: {i}" for g, i in orders.items()) + "}")
        only_if = {layouts[g].only_if for g in games if layouts[g].only_if}
        if only_if:
            args.append(f"only_if={lit(next(iter(only_if)))}")

        original = layouts[games[-1]].original_name
        if original is not None and original != inflection.camelize(
            _BASE_NAME_SUFFIX.sub("", field.split_from or field.name)
        ):
            args.append(f"original_name={lit(original)}")

        name = field.name
        return wrap_call(f"    {name}: {annotation} = {self.codec_name('prop')}", args)

    def render_class(self, cls: MClass) -> list[str]:
        is_object = cls.is_object
        base = "BaseObjectType" if is_object else "BaseStruct"
        self.bases.add(base)
        kwargs: list[str] = []
        if is_object:
            items = ", ".join(
                f"{self.game_const(g)}: {lit(v)}" if isinstance(v, str) else f"{self.game_const(g)}: {hex(v)}"
                for g, v in cls.object_types.items()
            )
            kwargs.append(f"object_types={{{items}}}")
        modules = {g: c.modules for g, c in cls.per_game.items() if c.modules is not None}
        if modules:
            kwargs.append("modules={" + ", ".join(f"{self.game_const(g)}: {lit(m)}" for g, m in modules.items()) + "}")
        atomic = [g for g, c in cls.per_game.items() if c.atomic]
        if atomic:
            expr = self.games_expr(atomic)
            kwargs.append(f"atomic={expr if len(atomic) > 1 else '{' + expr + '}'}")
        field_games = {g for f in cls.fields for g in f.layouts}
        declared = set(cls.object_types) | field_games
        if set(cls.games) != declared:
            kwargs.append(f"games={self.games_expr(cls.games)}")
        lines = ["@dataclasses.dataclass()", wrap_call(f"class {cls.final_name}", [base, *kwargs], ":")]
        body = [self.render_field(cls, f) for f in cls.fields]
        if any(c.incomplete for c in cls.per_game.values()):
            body.append(f"    unknown_properties: dict[int, bytes] = {self.codec_name('unknown_properties')}()")
        lines.extend(body or ["    pass"])
        return lines


def game_order(cls: MClass, game: Game) -> list[str]:
    """The names of the fields of the class in the order the game's template has them."""
    by_layout = {id(lay): f.name for f in cls.fields for lay in f.layouts.values()}
    return [by_layout[id(f)] for f in cls.per_game[game].fields]


def _order_nested(classes: list[MClass]) -> list[MClass]:
    """Orders classes so each comes after the ones its fields refer to."""
    by_name = {c.name: c for c in classes}
    result: list[MClass] = []
    state: dict[str, int] = {}

    def visit(cls: MClass) -> None:
        if state.get(cls.name) == 2:
            return
        if state.get(cls.name) == 1:
            raise ValueError(f"Circular reference of structs in {cls.name}")
        state[cls.name] = 1
        for ref in sorted(cls.struct_refs()):
            if ref in by_name:
                visit(by_name[ref])
        state[cls.name] = 2
        result.append(cls)

    for cls in sorted(classes, key=lambda c: c.name):
        visit(cls)
    return result


def _from_import(module: str, names: list[str]) -> str:
    one_line = f"from {module} import {', '.join(names)}"
    if len(one_line) <= LINE_LENGTH:
        return one_line
    inner = ", ".join(names)
    if 4 + len(inner) <= LINE_LENGTH:
        return f"from {module} import (\n    {inner}\n)"
    return f"from {module} import (\n" + "".join(f"    {n},\n" for n in names) + ")"


def _sorted_names(names: typing.Iterable[str]) -> list[str]:
    return sorted(names, key=lambda n: (0 if n.isupper() else 1 if n[:1].isupper() else 2, n.lower(), n))


def module_source(merged: Merged, names: Names, module: str, classes: list[MClass]) -> str:
    """The module with the classes in it, in order, and the local enums of them."""
    builder = ModuleBuilder(merged, names, module, "")
    field_names = {f.name for c in classes for f in c.fields}
    builder.shadowed = field_names & CODEC_HELPERS
    class_names = {c.name for c in classes}
    local_enums = sorted((e for e in merged.enums.values() if e.owner in class_names), key=lambda e: e.final_name)

    body: list[str] = []
    for e in local_enums:
        body.append("\n".join(render_enum(e)))
    for cls in classes:
        body.append("\n".join(builder.render_class(cls)))

    imports: dict[str, set[str]] = collections.defaultdict(set)
    for mod, name in builder.class_imports:
        imports[mod].add(name)
    if builder.bases:
        imports[f"{PACKAGE}.base_property"].update(builder.bases)
    codec_imports = set(builder.constants)
    for name in builder.codec_names:
        codec_imports.add(f"{name} as _{name}" if name in builder.shadowed else name)
    if codec_imports:
        imports[f"{PACKAGE}.codec"].update(codec_imports)
    for core in builder.core:
        imports[CORE_TYPES[core]].add(core)
    if any(not e.plain for e in local_enums):
        imports["retro_data_structures.game_check"].add("Game")
    if any(e.allow_unknown for e in local_enums):
        imports["retro_data_structures.enums.merged"].add("AllowUnknownValues")

    stdlib = ["import dataclasses"]
    if local_enums:
        stdlib.append("import enum")
    import_lines = [_from_import(m, _sorted_names(n)) for m, n in sorted(imports.items(), key=lambda kv: kv[0].lower())]
    parts = [HEADER, "from __future__ import annotations\n", "\n".join(stdlib) + "\n"]
    if import_lines:
        parts.append("\n".join(import_lines) + "\n")
    text = "\n".join(parts)
    return text + "\n\n" + "\n\n\n".join(body) + "\n"


def object_tables_source(merged: Merged, names: Names) -> str:
    tables: dict[Game, dict[typing.Any, str]] = {g: {} for g in GAMES}
    for cls in merged.classes.values():
        for game, object_type in cls.object_types.items():
            tables[game][object_type] = cls.final_name
        for game, aliases in cls.alias_object_types.items():
            for alias in aliases:
                tables[game][alias] = cls.final_name

    lines = [
        HEADER,
        "from __future__ import annotations\n",
        "import functools\nimport importlib\nimport typing\n",
        "from retro_data_structures.game_check import Game\n",
        "if typing.TYPE_CHECKING:\n    from retro_data_structures.properties.base_property import BaseObjectType\n",
    ]
    out = "\n".join(lines)
    for game in GAMES:
        table = tables[game]
        key_type = "int" if game == Game.PRIME else "str"
        entries = [
            f"{(hex(k) if game == Game.PRIME else lit(k))}: {lit(v)}"
            for k, v in sorted(table.items(), key=lambda kv: kv[0])
        ]
        out += f"\n_{game.name}: dict[{key_type}, str] = {{\n" + "\n".join(fill_lines(entries, "    ")) + "\n}\n"
    out += (
        "\n_TABLES: dict[Game, dict[typing.Any, str]] = {\n"
        + "".join(f"    Game.{g.name}: _{g.name},\n" for g in GAMES)
        + "}\n"
    )
    out += '''

@functools.cache
def get_object(game: Game, object_type: str | int) -> type[BaseObjectType]:
    """The class of the script object with the type in the game. Modules are imported on first use."""
    name = _TABLES[game][object_type]
    return typing.cast("type[BaseObjectType]", getattr(importlib.import_module(f"{__name__}.{name}"), name))
'''
    return out


def collect_modules(merged: Merged) -> dict[tuple[str, str], list[MClass]]:
    """(package, name) -> classes of the module."""
    modules: dict[tuple[str, str], list[MClass]] = {}
    for cls in merged.classes.values():
        if cls.placement == "archetypes":
            modules[("archetypes", cls.final_name)] = [cls]
        elif cls.placement == "objects":
            modules.setdefault(("objects", cls.final_name), [])
        else:
            root = merged.classes[cls.placement].final_name
            modules.setdefault(("objects", root), [])
    for cls in merged.classes.values():
        if cls.placement not in ("archetypes",):
            root = cls.final_name if cls.placement == "objects" else merged.classes[cls.placement].final_name
            modules[("objects", root)].append(cls)
    for key, classes in modules.items():
        if key[0] == "objects":
            modules[key] = _order_nested(classes)
    return modules
