"""The merge report: what the merge had to decide, so the templates can be fixed."""

from __future__ import annotations

import collections
import difflib
import typing

from retro_data_structures.game_check import Game

if typing.TYPE_CHECKING:
    from pwe_generator.merge import Merged


def _games(games: typing.Iterable[typing.Any]) -> str:
    return ", ".join(g.name for g in sorted(games, key=lambda g: g.value))


def _type_name(type_key: tuple) -> str:
    if type_key[0] == "list":
        return f"list[{_type_name(type_key[1])}]"
    if type_key[0] in ("enum", "struct"):
        ref = type_key[1]
        return ref if isinstance(ref, str) else ref[-1]
    return str(type_key[0])


def build_report(merged: Merged) -> str:  # noqa: C901, PLR0912, PLR0915
    out: list[str] = ["# Merge report", "", "Generated by `parse_pwe_templates.py`. Do not edit.", ""]
    classes = merged.classes

    counts = collections.Counter(c.kind for c in classes.values())
    multi = sum(1 for c in classes.values() if len(c.games) > 1)
    field_count = sum(len(c.fields) for c in classes.values())
    per_game_fields = sum(len(f.layouts) for c in classes.values() for f in c.fields)
    out += [
        "## Summary",
        "",
        (
            f"- classes: {len(classes)} ({counts['object']} objects, {counts['tweak']} tweaks and scans, "
            f"{counts['struct']} structs), {multi} in more than one game"
        ),
        f"- fields: {field_count} merged, from {per_game_fields} per game",
        f"- enums and flags: {len(merged.enums)}",
        "",
    ]

    # 1. Split fields
    splits = sorted(merged.report.get("split", []))
    out += [
        f"## 1. Split fields (type conflicts): {len(splits)}",
        "",
        "The variant used by the most games keeps the name. The others have the type in their name.",
        "",
    ]
    out += [f"- {line}" for line in splits] or ["None."]
    out.append("")

    # 2. Fields in a single game with a counterpart in another
    pairs: list[str] = []
    for cls in sorted(classes.values(), key=lambda c: c.name):
        if len(cls.games) < 2:
            continue
        exclusive = [f for f in cls.fields if len(f.layouts) == 1]
        for i, a in enumerate(exclusive):
            (game_a,) = a.layouts
            for b in exclusive[i + 1 :]:
                (game_b,) = b.layouts
                if game_a == game_b or a.type_key != b.type_key:
                    continue
                index_a = [f.name for f in cls.fields if game_a in f.layouts].index(a.name)
                index_b = [f.name for f in cls.fields if game_b in f.layouts].index(b.name)
                similar = difflib.SequenceMatcher(None, a.name, b.name).ratio()
                if index_a == index_b or similar >= 0.7:
                    pairs.append(
                        f"{cls.name}: `{a.name}` ({game_a.name}, #{index_a}) ~ `{b.name}` ({game_b.name}, #{index_b}) "
                        f"[{_type_name(a.type_key)}]"
                    )
    out += [
        f"## 2. Fields in only one game, with a same-type field in another game: {len(pairs)}",
        "",
        (
            "Same type, and either the same position in the class or a similar name. Candidates for a rename in the "
            "templates."
        ),
        "",
    ]
    out += [f"- {line}" for line in pairs] or ["None."]
    out.append("")

    # 3. Classes with different fields
    differing: list[str] = []
    for cls in sorted(classes.values(), key=lambda c: c.name):
        if len(cls.games) < 2:
            continue
        shared = [f for f in cls.fields if len(f.layouts) == len(cls.games)]
        if len(shared) == len(cls.fields):
            continue
        only = {g: [f.name for f in cls.fields if f.layouts.keys() == {g}] for g in cls.games}
        parts = [f"only {g.name}: {len(n)}" for g, n in only.items() if n]
        partial = [f for f in cls.fields if 1 < len(f.layouts) < len(cls.games)]
        if partial:
            parts.append(f"{len(partial)} in some of the games")
        differing.append(f"{cls.name} ({cls.kind}, {_games(cls.games)}): {len(shared)} shared; " + "; ".join(parts))
    out += [f"## 3. Classes of more than one game whose fields differ: {len(differing)}", ""]
    out += [f"- {line}" for line in differing] or ["None."]
    out.append("")

    # 4. Enums
    differing_enums: list[str] = []
    for e in sorted(merged.enums.values(), key=lambda e: e.final_name):
        if e.plain:
            continue
        games = sorted(e.game_values, key=lambda g: g.value)
        missing = {g.name: sorted(set(e.members) - set(e.game_values[g])) for g in games}
        changed = sorted(
            n for n in e.members if len({repr(e.game_values[g][n]) for g in games if n in e.game_values[g]}) > 1
        )
        parts = [f"in {_games(games)}"]
        for g, names in missing.items():
            if names:
                parts.append(f"{g} lacks {len(names)}")
        if changed:
            parts.append(f"{len(changed)} members with different values")
        if e.renumbered:
            parts.append(f"renumbered: {', '.join(e.renumbered)}")
        differing_enums.append(f"{e.final_name} ({e.kind}): " + "; ".join(parts))
    out += [f"## 4. Enums and flags that differ between games: {len(differing_enums)}", ""]
    out += [f"- {line}" for line in differing_enums] or ["None."]
    out.append("")

    # Other decisions
    other: list[str] = []
    other += [f"kind differs: {line}" for line in sorted(merged.report.get("kind", []))]
    other += [f"names that differ in case: {line}" for line in sorted(merged.report.get("case", []))]
    for cls in sorted(classes.values(), key=lambda c: c.name):
        if cls.order_games:
            other.append(f"{cls.name}: explicit `order` for {_games(cls.order_games)}")
    for _, e in sorted(merged.enums.items()):
        if e.final_name != e.name:
            other.append(f"enum {e.name} is called {e.final_name} (name taken)")
    for cls in sorted(classes.values(), key=lambda c: c.name):
        prime = cls.per_game.get(Game.PRIME)
        if prime is not None and prime.count_issue:
            other.append(f"{cls.name}: Prime properties with a count condition stay required ({prime.count_issue})")
        optional = [f.name for f in prime.fields if f.min_count is not None] if prime is not None else []
        if optional:
            other.append(f"{cls.name}: optional Prime properties (by property count): {', '.join(optional)}")
    out += [f"## 5. Other decisions: {len(other)}", ""]
    out += [f"- {line}" for line in other] or ["None."]
    out.append("")
    return "\n".join(out)
